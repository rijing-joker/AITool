test("incomplete or inconsistent parents leave the child cursor untouched and retry", async (t) => {
  const x = await fixture(t);
  await x.write(x.page, [meta(PARENT, 20), token(21, 300)]);
  await x.write(x.child, x.childRows);
  const cursors = { files: {} }, queue = path.join(x.home, "queue.jsonl");
  assert.equal((await parseRolloutIncremental({ rolloutFiles: [x.child, x.page, x.root], cursors, queuePath: queue })).deferredFiles, 1);
  assert.equal(cursors.files[x.child], undefined);
  await fs.appendFile(x.page, JSON.stringify(context(40)) + "\n");
  await parseRolloutIncremental({ rolloutFiles: [x.child, x.page, x.root], cursors, queuePath: queue });
  assert.equal(await queueTotal(queue), 330);
  const copy = path.join(x.home, path.basename(x.page));
  await x.write(copy, [meta(PARENT, 20), token(21, 900), context(40)]);
  const resolve = createForkReplayResolver([x.root, x.page, copy]);
  await assert.rejects(resolve({ forked_from_id: PARENT }, ts(30)), /copies disagree/);
});
