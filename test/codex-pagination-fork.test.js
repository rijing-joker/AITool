test("native spawned-thread lineage excludes replay across sync, analytics and transcript reads", async (t) => {
  const x = await fixture(t);
  const childMeta = meta(CHILD, 30);
  childMeta.payload.source = { subagent: { thread_spawn: { parent_thread_id: PARENT } } };
  const childRows = [childMeta, ...x.childRows.slice(1)];
  const inventory = [x.child, x.page, x.root];
  await x.write(x.child, childRows.slice(0, 3));
  const queue = path.join(x.home, "spawned-queue.jsonl");
  const cursors = { files: {} };
  await parseRolloutIncremental({ rolloutFiles: inventory, cursors, queuePath: queue });
  const resolver = createForkReplayResolver(inventory);
  const first = await parseCodexRolloutFile(x.child, { resolveForkReplay: resolver, captureResumeState: true });
  assert.equal(first.totals.total_tokens, 0);
  assert.equal(first.parentThreadId, PARENT);
  await fs.appendFile(x.child, childRows.slice(3).map(JSON.stringify).join("\n") + "\n");
  const resumed = await parseCodexRolloutFile(x.child, { resolveForkReplay: resolver, resumeState: first.resumeState, startOffset: first.endOffset });
  assert.equal(resumed.totals.total_tokens, 30);
  await parseRolloutIncremental({ rolloutFiles: inventory, cursors, queuePath: queue });
  assert.equal(await queueTotal(queue), 330);
  assert.equal((await parseRolloutIncremental({ rolloutFiles: inventory, cursors, queuePath: queue })).eventsAggregated, 0);
  const rows = await buildSessionAnalytics({ home: x.home, force: true });
  const child = rows.find((row) => row.session_id === CHILD);
  assert.equal(child.total_tokens, 30);
  assert.equal(child.parent_session_id, PARENT);
  const transcript = await require("../src/lib/sessions").readSession({ app: "codex", sourcePath: x.child, home: x.home });
  assert.equal(transcript.usage.totalTokens, 30);
});
test("conflicting native spawned-thread parents defer counting and preserve the cursor", async (t) => {
  const x = await fixture(t);
  x.childRows[0].payload.source = { subagent: { thread_spawn: { parent_thread_id: PAGE } } };
  await x.write(x.child, x.childRows);
  const inventory = [x.child, x.page, x.root];
  await assert.rejects(parseCodexRolloutFile(x.child, { resolveForkReplay: createForkReplayResolver(inventory) }), /Conflicting Codex parent/);
  const cursors = { files: {} };
  const result = await parseRolloutIncremental({ rolloutFiles: inventory, cursors, queuePath: path.join(x.home, "conflict-queue.jsonl") });
  assert.equal(result.deferredFiles, 1);
  assert.equal(cursors.files[x.child], undefined);
  const transcript = await require("../src/lib/sessions").readSession({ app: "codex", sourcePath: x.child, home: x.home });
  assert.equal(transcript.usage, null);
});
