"use strict";
const { test } = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const path = require("node:path");
const os = require("node:os");
const sessions = require("../src/lib/sessions");
const { readDshSessions } = require("../src/lib/dsh-session");
const at = Date.UTC(2026, 9, 29);
const user = { type: "user/message", time: at + 1, data: { id: "u", role: "user", content: [{ type: "text", text: "Fix the test" }], source: { kind: "user" } } };
const assistant = (id, text) => ({ type: "assistant/message", time: at + 2, data: { message: { id, source: { model: "deepseek/test" }, content: [{ type: "text", text }] }, usage: { inputTokens: 10, cacheReadTokens: 2, outputTokens: 3, reasoningTokens: 1 } } });
test("DSH transcript replay usage is deduped across logs and revisions include newly discovered parents", async t => {
  const home = await fs.mkdtemp(path.join(os.tmpdir(), "aitool-dsh-test-"));
  t.after(() => fs.rm(home, { recursive: true, force: true }));
  const write = async (id, rows, compressed = false) => {
    const file = path.join(home, ".dsh", "sessions", "project", id, compressed ? "session.v2.jsonl.zstd" : "session.jsonl");
    await fs.mkdir(path.dirname(file), { recursive: true });
    const raw = Buffer.from(rows.map(JSON.stringify).join("\n") + "\n");
    await fs.writeFile(file, compressed ? await require("@mongodb-js/zstd").compress(raw, 3) : raw);
    return file;
  };
  const child = await write("child", [{ type: "session", id: "session-child", createdAt: at + 100, cwd: "/fixture" }, user, assistant("a", "Replayed"), assistant("a", "Replayed"), assistant("b", "Own answer"), { type: "user/message", time: at + 3, data: { id: "inject", content: [{ type: "text", text: "Runtime context" }], source: { kind: "plugin" } } }], true);
  const options = { app: "dsh", sourcePath: child, home, env: {} };
  const preview = await sessions.readSession({ ...options, preview: true });
  assert.equal(preview.usage.inputTokens, 20);
  assert.deepEqual(preview.messages.filter(row => !row.injected).map(row => row.content), ["Fix the test", "Replayed", "Own answer"]);
  const parent = await write("parent", [{ type: "session", id: "session-parent", createdAt: at, cwd: "/fixture" }, user, assistant("a", "Replayed")]);
  const updated = await sessions.readSession(options);
  assert.notEqual(updated.revision, preview.revision);
  assert.equal(updated.usage.inputTokens, 10);
  assert.equal(updated.usage.totalTokens, 16);
  const pricing = { test: { input: 1, output: 2, cacheRead: 0.1, cacheWrite: 1.25 } };
  require("../src/lib/session-pricing").priceSessionUsage(updated.usage, pricing);
  assert.equal(updated.usage.inputInclusive, false);
  assert.equal(updated.usage.estimatedCostUsd, (10 + 2 * 0.1 + (3 + 1) * 2) / 1e6);
  const rows = await readDshSessions([parent, child]);
  assert.equal(rows.reduce((sum, row) => sum + row.tokens.input_tokens, 0), 20);
  assert.equal(rows.reduce((sum, row) => sum + row.turns, 0), 1);
  assert.equal(JSON.stringify(rows).includes("Fix the test"), false);
  assert.equal((await sessions.listSessions({ app: "dsh", home, env: {} })).length, 2);
  const outside = path.join(home, "outside.jsonl");
  await fs.copyFile(parent, outside); await fs.unlink(parent); await fs.symlink(outside, parent);
  await assert.rejects(sessions.readSession({ ...options, sourcePath: parent }), /outside|root|symlink/i);
});
