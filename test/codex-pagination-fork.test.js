test("transcript reader merges physical pages, excludes replay billing and clamps every page", async (t) => {
  const x = await fixture(t);
  const message = (time, content) => ({ type: "response_item", timestamp: ts(time), payload: { type: "message", role: "user", content: [{ type: "input_text", text: content }] } });
  await fs.appendFile(x.root, JSON.stringify(message(2, "first page")) + "\n");
  await fs.appendFile(x.page, JSON.stringify(message(22, "second page")) + "\n");
  await x.write(x.child, [...x.childRows, message(34, "child turn")]);
  const reader = require("../src/lib/sessions");
  const rows = await reader.listSessions({ app: "codex", home: x.home });
  assert.equal(rows.filter((row) => row.sessionId === PARENT).length, 1);
  const parent = await reader.readSession({ app: "codex", sourcePath: x.page, home: x.home });
  assert.deepEqual(parent.messages.map((row) => row.content), ["first page", "second page"]);
  assert.equal(parent.usage.totalTokens, 300);
  const child = await reader.readSession({ app: "codex", sourcePath: x.child, home: x.home });
  assert.equal(child.usage.totalTokens, 30);
  const outside = path.join(x.home, "outside.jsonl");
  await x.write(outside, [message(50, "outside secret"), token(50, 999)]);
  const link = path.join(path.dirname(x.page), `rollout-2026-10-10T03-00-50-${PARENT}_44444444-4444-4444-8444-444444444444.jsonl`);
  await fs.symlink(outside, link);
  const safe = await reader.readSession({ app: "codex", sourcePath: x.root, home: x.home });
  assert.doesNotMatch(JSON.stringify(safe), /outside secret/);
  assert.equal(safe.usage.totalTokens, 300);
});
