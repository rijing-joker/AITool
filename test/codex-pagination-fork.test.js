const { test } = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const os = require("node:os");
const path = require("node:path");
const { createForkReplayResolver } = require("../src/lib/codex-fork-replay");
const { parseCodexRolloutFile } = require("../src/lib/codex-rollout-parser");
const { parseRolloutIncremental } = require("../src/lib/rollout");
const { buildSessionAnalytics, discoverSessionFiles } = require("../src/lib/session-analytics");
const { rolloutIds } = require("../src/lib/codex-rollout-file");
const PARENT = "11111111-1111-4111-8111-111111111111";
const PAGE = "22222222-2222-4222-8222-222222222222";
const CHILD = "33333333-3333-4333-8333-333333333333";
const ts = (seconds) => new Date(Date.UTC(2026, 9, 10, 3, 0, seconds)).toISOString();
const usage = (input, output = 0) => ({ input_tokens: input, output_tokens: output, total_tokens: input + output });
const meta = (id, time, parent) => ({ type: "session_meta", timestamp: ts(time), payload: { id, cwd: "/repo", ...(parent ? { forked_from_id: parent } : {}) } });
const context = (time) => ({ type: "turn_context", timestamp: ts(time), payload: { model: "gpt-5.5", current_date: "2026-10-10" } });
const token = (time, total, last) => ({ type: "event_msg", timestamp: ts(time), payload: { type: "token_count", info: { total_token_usage: usage(total), ...(last === undefined ? {} : { last_token_usage: usage(last) }) } } });
async function fixture(t) {
  const home = await fs.mkdtemp(path.join(os.tmpdir(), "aitool-codex-pages-"));
  t.after(() => fs.rm(home, { recursive: true, force: true }));
  const directory = path.join(home, ".codex/sessions/2026/10/10");
  await fs.mkdir(directory, { recursive: true });
  const root = path.join(directory, `rollout-2026-10-10T03-00-00-${PARENT}.jsonl`);
  const page = path.join(directory, `rollout-2026-10-10T03-00-20-${PARENT}_${PAGE}.jsonl`);
  const child = path.join(directory, `rollout-2026-10-10T03-00-30-${CHILD}.jsonl`);
  const write = (file, rows) => fs.writeFile(file, rows.map(JSON.stringify).join("\n") + "\n");
  await write(root, [meta(PARENT, 0), context(0), token(1, 100)]);
  await write(page, [meta(PARENT, 20), context(20), token(21, 300), context(40)]);
  const childRows = [meta(CHILD, 30, PARENT), context(30), token(31, 100), token(32, 300), token(33, 330)];
  return { home, root, page, child, childRows, write };
}
async function queueTotal(file) {
  const rows = (await fs.readFile(file, "utf8")).trim().split("\n").filter(Boolean).map(JSON.parse);
  const latest = new Map(rows.map((row) => [`${row.source}:${row.model}:${row.hour_start}`, row]));
  return [...latest.values()].reduce((total, row) => total + row.total_tokens, 0);
}
